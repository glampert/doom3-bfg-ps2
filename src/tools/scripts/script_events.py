"""Write src/tools/script_cook/events.txt from a bounded headless run's ps2_scriptEvents output."""

import argparse
from datetime import datetime, timezone
from pathlib import Path
import re
import subprocess
import sys
import time
import uuid

import run_pcsx2_test as smoke
from run_headless import SHUTDOWN_COMPLETE, read_log
from stage_headless import REPO_ROOT, stage

EVENT_RE = re.compile(r'\[D3BFG\] SCRIPT_EVENT "([^"]*)" "([^"]*)" (-?\d+) ([01])')
COUNT_RE = re.compile(r"\[D3BFG\] SCRIPT_EVENTS count=(\d+)")
DEFAULT_OUTPUT = REPO_ROOT / "src/tools/script_cook/events.txt"
HEADER = """# Generated by src/tools/scripts/script_events.py from the debug production ELF's event registry
# (the ps2_scriptEvents command); regenerate it after adding, removing or changing an idEventDef.
# Each line: name, argument format ('-' when empty), return type (a format character or '-' for
# void), and 1 when idThread responds to the event (a sys call). The PS2 checks every event the
# cooked program uses against its own registry at load.
"""


def parse(log: str) -> list[tuple[str, str, str, str]]:
    events = []
    for name, formats, returned, thread in EVENT_RE.findall(log):
        code = int(returned)
        if any(character.isspace() for character in name + formats) or not 0 <= code < 128:
            raise ValueError(f"event {name!r} cannot be written to the table")
        events.append((name, formats or "-", chr(code) if code else "-", thread))
    count = COUNT_RE.search(log)
    if count is None or int(count.group(1)) != len(events):
        raise ValueError("the event listing is incomplete")
    if len({name for name, _, _, _ in events}) != len(events):
        raise ValueError("the registry holds duplicate event names")
    return events


def run(args: argparse.Namespace) -> str:
    identity = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "_script_events_" + uuid.uuid4().hex[:12]
    output = stage("debug", REPO_ROOT / "build/test-results" / identity)
    # Game commands exist once game init has run, so the listing goes through the polled console
    # input rather than the startup config.
    (output / "base/d3bfg.cfg").write_text("")
    (output / "console.txt").write_bytes(b"ps2_scriptEvents\nquit\n")
    command = [str(args.emulator), "-batch", "-elf", str(output / "d3bfg.elf"), "-logfile", str(output / "emulog.txt")]
    started = time.monotonic()
    with (output / "stdout.txt").open("wb") as stdout:
        process = subprocess.Popen(command, cwd=output, stdout=stdout, stderr=subprocess.STDOUT)
        try:
            while time.monotonic() - started < args.timeout:
                log = read_log(output)
                if smoke.CRASH_RE.search(log):
                    raise ValueError(f"the run crashed or failed; see {output}")
                if SHUTDOWN_COMPLETE in log:
                    break
                if process.poll() is not None:
                    raise ValueError(f"the emulator exited before shutdown; see {output}")
                time.sleep(0.05)
            else:
                raise ValueError(f"watchdog timeout; see {output}")
        finally:
            smoke.stop_owned_process(process)
    return read_log(output)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--emulator", type=Path, default=smoke.DEFAULT_EMULATOR)
    parser.add_argument("--config", type=Path, default=smoke.DEFAULT_CONFIG)
    parser.add_argument("--timeout", type=float, default=60.0)
    parser.add_argument("--log", type=Path, help="parse an existing run's stdout instead of starting one")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    try:
        if args.log is not None:
            log = args.log.read_text(errors="replace")
        else:
            if smoke.emulator_is_running(args.emulator):
                raise ValueError("an emulator is already running; close it first")
            smoke.check_config(args.config)
            log = run(args)
        events = parse(log)
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"script_events: {error}", file=sys.stderr)
        return 1
    lines = [HEADER] + [" ".join(event) + "\n" for event in sorted(events)]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("".join(lines))
    print(f"Wrote {len(events)} events to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
